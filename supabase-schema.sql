-- 1) Daily token generator.
-- Tokens restart at 1 every morning. The advisory lock keeps the
-- counter correct even if two customers submit at the same second.
create or replace function get_next_token()
returns int
language plpgsql
as $$
declare
  n int;
begin
  perform pg_advisory_xact_lock(hashtext('stationery-queue-' || current_date::text));
  select coalesce(max(token_number), 0) + 1
    into n
    from queue_items
   where queue_date = current_date;
  return n;
end;
$$;

-- 2) Queue table
create table if not exists queue_items (
  id             uuid        default gen_random_uuid() primary key,
  queue_date     date        not null default current_date,
  token_number   int         not null default get_next_token(),
  customer_name  text        not null,
  phone_number   text,
  file_name      text        not null,
  file_url       text        not null,   -- storage path, e.g. documents/2026-10-13/<uuid>_notes.pdf
  file_size_bytes bigint,
  print_settings jsonb       not null default
                     '{"color": false, "copies": 1, "pages": "all", "double_sided": false, "note": ""}'::jsonb,
  status         text        not null default 'waiting'
                     check (status in ('waiting', 'printing', 'completed', 'cancelled')),
  created_at     timestamptz not null default now()
);

create index if not exists queue_items_day_idx
  on queue_items (queue_date, status, token_number);

-- 3) Realtime: lets the dashboard and customer status pages update live
alter publication supabase_realtime add table queue_items;

-- 4) Row Level Security
alter table queue_items enable row level security;

-- Customers (anonymous) may only INSERT new waiting jobs for today.
-- The check() blocks anyone from inserting pre-completed rows or
-- rows dated in the past/future.
drop policy if exists "queue_insert_anon" on queue_items;
create policy "queue_insert_anon" on queue_items
  for insert to anon
  with check (status = 'waiting' and queue_date = current_date);

-- Anyone may read the queue (the token board is public in the shop).
drop policy if exists "queue_select_anon" on queue_items;
create policy "queue_select_anon" on queue_items
  for select to anon
  using (true);

-- Status changes (printing / completed / cancelled) are done from the
-- admin page, which also uses the anon key in this simple setup.
-- !! For a stricter setup, delete this policy and use Supabase Auth
-- !! for the shop owner instead (see README hardening notes).
drop policy if exists "queue_update_anon" on queue_items;
create policy "queue_update_anon" on queue_items
  for update to anon
  using (true)
  with check (true);

-- 5) Storage bucket for the uploaded documents (private; downloads
--    go through 1-hour signed URLs generated by the admin page).
insert into storage.buckets (id, name, public)
values ('documents', 'documents', false)
on conflict (id) do nothing;

drop policy if exists "doc_upload_anon" on storage.objects;
create policy "doc_upload_anon" on storage.objects
  for insert to anon
  with check (bucket_id = 'documents');

drop policy if exists "doc_read_anon" on storage.objects;
create policy "doc_read_anon" on storage.objects
  for select to anon
  using (bucket_id = 'documents');

